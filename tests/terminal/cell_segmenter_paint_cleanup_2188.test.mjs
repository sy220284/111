import { strict as assert } from 'node:assert';
import { CellSegmenter } from '../../runtime/terminal/cell-segmenter.mjs';
import { test } from 'node:test';
test('真实终端单元与宽字符/BiDi 行为：_paint_cleanup.test', () => {
const s = new CellSegmenter({ screen: { widthMask: 3, narrow: 0, wide: 1, spacerTail: 2, spacerHead: 3, emptyCharIndex: 0, spacerCharIndex: 1, emptyWord: 0, tabWidth: 8 } });
const width = 6;
const chars = new Int32Array(16).map((_, i) => 100 + i);
const words = new Int32Array(16);
const segment = (id, w) => new Int32Array([id, w]);
const row = () => new Int32Array(width * 2);
const paint = (c, x, id, w) => s.paint(c, width, x, 0, segment(id, w), 1, undefined, chars, words);
const damage = (p) => ({ left: Math.floor(p / 1048576) % 65536, right: Math.floor(p / 68719476736), cursor: p % 1048576 });
let cells = row();
s.setCell(cells, width, 1, 0, 88, 1);
let p = paint(cells, 1, 1, 1);
assert.equal(cells[2], 101);
assert.equal(cells[4], 0);
assert.deepEqual(damage(p), { left: 1, right: 3, cursor: 2 });
cells = row();
s.setCell(cells, width, 1, 0, 88, 1);
p = paint(cells, 2, 1, 1);
assert.equal(cells[2], 0);
assert.equal(cells[4], 101);
assert.deepEqual(damage(p), { left: 1, right: 3, cursor: 3 });
cells = row();
s.setCell(cells, width, 2, 0, 88, 1);
p = paint(cells, 1, 1, 2);
assert.equal(cells[2], 101);
assert.equal(cells[4], 1);
assert.equal(cells[6], 0);
assert.deepEqual(damage(p), { left: 1, right: 4, cursor: 3 });
console.log(JSON.stringify({ status: 'pass', scenarios: 3, focus: 'text paint clears stale wide-char spacers and expands damage bounds' }));

});