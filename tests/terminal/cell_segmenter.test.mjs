import { strict as assert } from 'node:assert';
import { CellSegmenter } from '../../runtime/terminal/cell-segmenter.mjs';
const screen = { widthMask: 3, narrow: 0, wide: 1, spacerTail: 2, spacerHead: 3, emptyCharIndex: 0, spacerCharIndex: 1, emptyWord: 0, tabWidth: 8 };
const s = new CellSegmenter({ ambiguousIsNarrow: true, screen });
const cells = new Int32Array(64);
const runs = new Int32Array(64);
const input = 'e\u0301中\x1b[31m红\x1b[0m👩‍💻\tA';
const n = s.segment(input, cells, runs, false);
assert.equal(n, 6);
assert.deepEqual(Array.from({ length: n }, (_, i) => s.graphemes[cells[i * 2]]), ['e\u0301', '中', '红', '👩‍💻', '\t', 'A']);
assert.deepEqual(Array.from({ length: n }, (_, i) => cells[i * 2 + 1] & 255), [1, 2, 2, 2, 0, 1]);
assert.equal((cells[8 + 1] & 256) !== 0, true);
assert.equal(s.sgrKeys.some(x => x === '\x1b[31m'), true);
const output = new Int32Array(32 * 2);
const map = new Int32Array(s.graphemes.length).map((_, i) => i + 10);
const words = new Int32Array(16);
const packed = s.paint(output, 32, 0, 0, cells, n, undefined, map, words);
assert.ok(packed > 0);
assert.equal(output[0], map[cells[0]]);
assert.equal(output[1] & 3, 0, 'first character is narrow');
assert.equal(output[3] & 3, 1, 'second character occupies 2 columns');
assert.equal(output[5] & 3, 2, 'wide character trailing spacer');
const single = new Int32Array(12);
s.setCell(single, 6, 1, 0, 55, 1);
assert.equal(single[2], 55);
assert.equal(single[4], 1);
const small = new Int32Array(2), smallruns = new Int32Array(2);
assert.equal(s.segment('abc', small, smallruns, false), -3);
console.log(JSON.stringify({ status: 'pass', tests: 11, coverage: 'segment,Unicode,SGR,tab,width,paint,setCell,resize' }));